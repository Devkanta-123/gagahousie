-- ==============================================================================
-- 4. TABLE: tambola_tickets (Housie / Tambola Grids Linked to Main Draw Tickets)
-- ==============================================================================
-- Relation: Foreign key `ticket_id` references `tickets.ticket_id` with ON DELETE CASCADE.
-- Unique Relation: (ticket_id, sl_no) ensures each SL No (1 to 6) is unique per main draw ticket.
CREATE TABLE IF NOT EXISTS public.tambola_tickets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_id TEXT NOT NULL REFERENCES public.tickets(ticket_id) ON DELETE CASCADE,
    sl_no INT NOT NULL CHECK (sl_no >= 1 AND sl_no <= 12),
    serial_number TEXT NOT NULL,                                  -- e.g. 'SR-101'
    unique_code TEXT NOT NULL,                                    -- e.g. 'GH-8902'
    player_name TEXT NOT NULL DEFAULT 'Available',
    ticket_data JSONB NOT NULL DEFAULT '[]'::jsonb,              -- 3x9 grid matrix: [[1, null, 23...], ...]
    status TEXT NOT NULL DEFAULT 'Available',                     -- 'Available' / 'Booked' / 'Selected'
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL,
    CONSTRAINT unique_ticket_sl UNIQUE (ticket_id, sl_no)
);

-- Enable Row Level Security (RLS)
ALTER TABLE public.tambola_tickets ENABLE ROW LEVEL SECURITY;

-- Grants for tambola_tickets table
GRANT ALL ON TABLE public.tambola_tickets TO anon, authenticated, service_role;
GRANT ALL ON ALL SEQUENCES IN SCHEMA public TO anon, authenticated, service_role;

-- Index for fast lookup by main ticket ID and composite (ticket_id, sl_no)
CREATE INDEX IF NOT EXISTS idx_tambola_tickets_ticket_id ON public.tambola_tickets(ticket_id);
CREATE INDEX IF NOT EXISTS idx_tambola_tickets_ticket_sl ON public.tambola_tickets(ticket_id, sl_no);

