-- 9. AUTO-CREATE WALLET TRIGGER FOR NEW REGISTERED USERS
-- ==============================================================================
CREATE OR REPLACE FUNCTION public.handle_new_user_wallet()
RETURNS TRIGGER AS $$
BEGIN
    INSERT INTO public.wallets (user_id, user_email, balance, currency, status)
    VALUES (NEW.id, NEW.email, 0.00, 'INR', 'active')
    ON CONFLICT (user_id) DO NOTHING;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

DROP TRIGGER IF EXISTS on_user_auth_created_wallet ON public.user_auth;
CREATE TRIGGER on_user_auth_created_wallet
    AFTER INSERT ON public.user_auth
    FOR EACH ROW EXECUTE FUNCTION public.handle_new_user_wallet();


