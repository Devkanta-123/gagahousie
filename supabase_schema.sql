CREATE POLICY "Allow public insert for registration" 
    ON public.user_auth 
    FOR INSERT 
    TO anon, authenticated
    WITH CHECK (true);

-- 6. Policy: Allow update
DROP POLICY IF EXISTS "Allow users to update their auth" ON public.user_auth;
CREATE POLICY "Allow users to update their auth" 
    ON public.user_auth 
    FOR UPDATE 
    TO anon, authenticated
    USING (true);

